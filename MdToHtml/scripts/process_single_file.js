// Helper: Rename URL-encoded files and directories to Chinese
// We reuse this logic from generate_portable_output.js
function renameEncodedItems(dir) {
    const items = fs.readdirSync(dir);
    
    items.forEach(item => {
        const fullPath = path.join(dir, item);
        const stat = fs.statSync(fullPath);
        
        if (item.includes('%')) {
            try {
                const decodedName = decodeURIComponent(item);
                if (decodedName !== item) {
                    const newPath = path.join(dir, decodedName);
                    if (fs.existsSync(newPath)) {
                        fs.rmSync(newPath, { recursive: true, force: true });
                    }
                    fs.renameSync(fullPath, newPath);
                    if (stat.isDirectory()) {
                         renameEncodedItems(newPath);
                    }
                    return; 
                }
            } catch (e) {
                console.error(`重命名失败: ${item}`, e);
            }
        }

        if (stat.isDirectory()) {
            renameEncodedItems(fullPath);
        }
    });
}

// Main processing function
async function processFiles() {
    console.log('开始处理静态网页...');
    
    // 0. Initial rename to ensure we work with correct filenames
    renameEncodedItems(OUTPUT_DIR);

    // Clean up unwanted .txt files (RSC payloads)
    function cleanUnwantedFiles(dir) {
        if (!fs.existsSync(dir)) return;
        const files = fs.readdirSync(dir);
        files.forEach(file => {
            const filePath = path.join(dir, file);
            const stat = fs.statSync(filePath);
            if (stat.isDirectory()) {
                cleanUnwantedFiles(filePath);
            } else {
                if (path.extname(file) === '.txt' && file !== 'README.txt') {
                    fs.unlinkSync(filePath);
                }
            }
        });
    }
    cleanUnwantedFiles(OUTPUT_DIR);
    
    // 1. Get all HTML files in output directory
    const htmlFiles = fs.readdirSync(OUTPUT_DIR).filter(f => f.endsWith('.html'));
    
    for (const file of htmlFiles) {
        if (file === '404.html') continue; // Skip 404
        
        const filePath = path.join(OUTPUT_DIR, file);
        const fileName = path.basename(file, '.html');
        console.log(`Processing: ${file}`);
        
        // 2. Read the exported HTML
        const content = fs.readFileSync(filePath, 'utf8');
        
        // 3. Parse with JSDOM to extract the main content
        const dom = new JSDOM(content);
        const doc = dom.window.document;
        
        // We need to find the main content container. 
        // Based on the source code, it's usually inside <div class="chd-renderer-root"> or similar.
        // Or we can just grab the entire body content, but we want to strip Next.js scripts.
        
        // In the static export, the content is rendered.
        // Let's try to find the CHDRenderer root or just take the body and strip scripts.
        
        // Remove Next.js scripts
        const scripts = doc.querySelectorAll('script');
        scripts.forEach(script => script.remove());
        
        // Remove Next.js hidden data
        const nextData = doc.getElementById('__NEXT_DATA__');
        if (nextData) nextData.remove();
        
        // Extract body content
        // We specifically want the rendered content.
        // If we look at the raw export, it has a lot of wrapper divs.
        // Ideally we want to find the container that corresponds to the 'editor preview'.
        // But for safety, let's take the body content and wrap it.
        let bodyContent = doc.body.innerHTML;
        
        // 4. Construct the new HTML
        const theme = 'ocean'; // Default theme, or try to detect from metadata?
        // Ideally we should match the theme used in the post, but that info is in the frontmatter.
        // For now, we use a safe default.
        
        const themeScript = `
            // Force sync theme
            document.documentElement.setAttribute('data-theme', '${theme}');
        `;
        
        const fullHtml = HTML_TEMPLATE
            .replace('{{TITLE}}', fileName)
            .replace('{{THEME}}', theme)
            .replace('{{CONTENT}}', bodyContent)
            .replace('{{CSS}}', GLOBAL_CSS) // Inject the extracted CSS
            .replace('{{THEME_SCRIPT}}', themeScript)
            .replace('{{SCRIPT}}', `
                document.addEventListener('DOMContentLoaded', () => {
                    console.log('Document loaded (Single File Mode)');
                });
            `);
            
        // 5. Overwrite the file
        fs.writeFileSync(filePath, fullHtml, 'utf8');
    }
    
    // 6. Cleanup and Organization
    console.log('正在整理文件...');
    const SYSTEM_DIR = path.join(OUTPUT_DIR, 'system');
    if (!fs.existsSync(SYSTEM_DIR)) {
        fs.mkdirSync(SYSTEM_DIR, { recursive: true });
    }

    const files = fs.readdirSync(OUTPUT_DIR);
    
    // System files to move
    const systemFiles = ['404.html', 'index.html', 'editor.html', 'preview.html', 'test.html'];
    
    // Directories to remove
    const dirsToRemove = ['_next', 'api'];

    files.forEach(file => {
        const filePath = path.join(OUTPUT_DIR, file);
        const stat = fs.statSync(filePath);

        // Move system files
        if (systemFiles.includes(file)) {
            const destPath = path.join(SYSTEM_DIR, file);
            if (fs.existsSync(destPath)) fs.unlinkSync(destPath);
            fs.renameSync(filePath, destPath);
            return;
        }

        // Remove .txt files
        if (file.endsWith('.txt')) {
            fs.unlinkSync(filePath);
            return;
        }

        // Remove directories
        if (stat.isDirectory()) {
            if (dirsToRemove.includes(file)) {
                fs.rmSync(filePath, { recursive: true, force: true });
            }
        }
    });

    console.log('静态网页处理完成。');
}

processFiles().catch(console.error);
