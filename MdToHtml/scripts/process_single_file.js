// 1. Load CSS from Next.js build
// We need to find the main CSS file generated by Next.js
function getBuildCss() {
    const staticCssDir = path.join(NEXT_BUILD_DIR, 'static/css');
    if (!fs.existsSync(staticCssDir)) return '';
    
    let cssContent = '';
    const files = fs.readdirSync(staticCssDir);
    files.forEach(file => {
        if (file.endsWith('.css')) {
            cssContent += fs.readFileSync(path.join(staticCssDir, file), 'utf8');
        }
    });
    return cssContent;
}

